// 2. Thuật toán giải mã với Control Flow Flattening (CFF) + MBA Identity
__attribute__((always_inline)) static inline std::string decryptF4fString(const uint8_t* data, size_t len, uint8_t baseKey, uint8_t stepVal) {
    std::string result;
    result.resize(len);
    volatile uint32_t state = 0x89ABCDEF;
    size_t idx = 0;
    while (state != 0) {
        switch (state) {
            case 0x89ABCDEF: {
                idx = 0;
                state = 0x23456789;
                break;
            }
            case 0x23456789: {
                state = (idx < len) ? 0xABCDEF01 : 0xDEAD0F4F;
                break;
            }
            case 0xABCDEF01: {
                uint8_t k = (baseKey + (uint8_t)(idx * stepVal)) & 0xFF;
                uint8_t raw = data[idx];
                // Mixed Boolean-Arithmetic (MBA) identity tương đương XOR: (a | b) - (a & b)
                uint8_t dec = (raw | k) - (raw & k);
                result[idx] = (char)dec;
                idx++;
                state = 0x23456789;
                break;
            }
            case 0xDEAD0F4F: {
                state = 0;
                break;
            }
            default: {
                state = 0;
                break;
            }
        }
    }
    return result;
}

